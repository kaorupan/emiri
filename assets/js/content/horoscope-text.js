  function dateLabel(d) { return d.year + "年" + d.month + "月" + d.day + "日"; }
  function pad2(n) { return n < 10 ? "0" + n : String(n); }
  function degLabel(p) { return p.sign + " " + p.degree + "°" + pad2(p.minute) + "′" + (p.retrograde ? "（逆行）" : ""); }

  function balanceView(r) {
    var els = ["火", "地", "風", "水"].map(function (e) { return { name: e, count: r.elements[e] }; });
    var qs = ["活動", "不動", "柔軟"].map(function (q) { return { name: q, count: r.qualities[q] }; });
    var maxE = Math.max.apply(null, els.map(function (e) { return e.count; }));
    var maxQ = Math.max.apply(null, qs.map(function (q) { return q.count; }));
    var texts = [];
    els.filter(function (e) { return e.count === maxE; }).forEach(function (e) { texts.push(["多いエレメント：" + e.name, ELEMENT[e.name]]); });
    els.filter(function (e) { return e.count === 0; }).forEach(function (e) { texts.push(["少ないエレメント：" + e.name, ELEMENT_NONE[e.name]]); });
    qs.filter(function (q) { return q.count === maxQ; }).forEach(function (q) { texts.push(["多いクオリティ：" + q.name, QUALITY[q.name]]); });
    return { elements: els, qualities: qs, total: 9, texts: texts };
  }

  function aspectView(a) {
    var key = a.a + "-" + a.b;
    var theme = PAIR_THEME[key] || (a.aName + "と" + a.bName);
    return { title: a.aName + " × " + a.bName + "：" + a.aspectName, tone: ASPECT_TYPE[a.aspect].tone, text: theme + "。" + ASPECT_TYPE[a.aspect].text, orb: a.orb };
  }

  /**
   * 表示用データ
   * @param {Object} r calculateHoroscope の結果
   * @param {Object} transit transits(今日) の結果（木星・土星の年運）
   */
  function buildHoroscopeView(r, transit) {
    var P = r.byKey;
    var sun = SUN[P.sun.sign];
    var notes = r.mayChange.map(function (k) {
      var p = P[k];
      return p.name + "は、この日のうちに" + p.mayChange.from + "から" + p.mayChange.to + "へ移ります。ここでは正午の位置（" + p.sign + "）で読んでいます。生まれた時刻が分かる場合は入力すると確定します。";
    });
    var view = {
      birthLabel: dateLabel(r.input) + (r.input.time ? " " + r.input.time.hour + ":" + pad2(r.input.time.minute) : ""),
      timeNote: r.input.time ? "" : "（時刻なし・正午で計算）",
      tradition: TRADITION,
      planets: r.planets.map(function (p) { return { key: p.key, name: p.name, sign: p.sign, position: degLabel(p), retrograde: p.retrograde, mayChange: !!p.mayChange }; }),
      notes: notes,
      sun: { sign: P.sun.sign, keyword: sun.keyword, body: sun.body },
      moon: { sign: P.moon.sign, body: MOON[P.moon.sign] },
      personal: [
        ["水星（考え方・話し方）：" + P.mercury.sign + (P.mercury.retrograde ? "・逆行" : ""), MERCURY[P.mercury.sign]],
        ["金星（愛し方・楽しみ方）：" + P.venus.sign + (P.venus.retrograde ? "・逆行" : ""), VENUS[P.venus.sign]],
        ["火星（行動力・情熱）：" + P.mars.sign + (P.mars.retrograde ? "・逆行" : ""), MARS[P.mars.sign]]
      ],
      social: [
        ["木星（幸運・成長）：" + P.jupiter.sign, JUPITER[P.jupiter.sign]],
        ["土星（試練・責任）：" + P.saturn.sign, SATURN[P.saturn.sign]]
      ],
      outer: ["uranus", "neptune", "pluto"].map(function (k) { return [OUTER[k] + P[k].sign, OUTER_SIGN[P[k].sign] + "世代。"]; }),
      balance: balanceView(r),
      aspects: r.aspects.map(aspectView)
    };
    if (transit) {
      var jh = ((transit.jupiter.signIndex - P.sun.signIndex) % 12 + 12) % 12;
      var sh = ((transit.saturn.signIndex - P.sun.signIndex) % 12 + 12) % 12;
      view.year = [
        ["いまの木星：" + transit.jupiter.sign + "（あなたの第" + (jh + 1) + "ハウス）", JUPITER_HOUSE[jh]],
        ["いまの土星：" + transit.saturn.sign + "（あなたの第" + (sh + 1) + "ハウス）", SATURN_HOUSE[sh]]
      ];
    }
    return view;
  }

  function buildHoroscopeCompatibilityView(c) {
    function person(r) {
      return { birthLabel: dateLabel(r.input) + (r.input.time ? " " + r.input.time.hour + ":" + pad2(r.input.time.minute) : ""), sun: r.byKey.sun.sign, moon: r.byKey.moon.sign, venus: r.byKey.venus.sign, mars: r.byKey.mars.sign, moonMayChange: !!r.byKey.moon.mayChange };
    }
    var soft = c.aspects.filter(function (a) { return a.aspect === "trine" || a.aspect === "sextile" || a.aspect === "conjunction"; }).length;
    var hard = c.aspects.length - soft;
    var lead = !c.aspects.length ? "ふたりの主な天体どうしには、目立つ角度がありません。強く引き合うというより、お互いのペースを尊重しながら、ゆっくり関係を育てていく組み合わせです。"
      : soft >= hard ? "ふたりの天体どうしには調和する角度が多く、一緒にいて心地よさを感じやすい組み合わせです。" + (hard ? "刺激し合う角度もあり、ほどよい緊張感が関係を新鮮に保ちます。" : "")
      : "ふたりの天体どうしには刺激し合う角度が多く、強く惹かれ合う情熱的な組み合わせです。すれ違いは話し合いで乗り越えるほど、絆が深まります。";
    return {
      you: person(c.person1), partner: person(c.person2),
      tradition: TRADITION.compat,
      lead: lead,
      sun: { label: SIGN_REL[c.sun].label, text: "太陽どうし（" + c.person1.byKey.sun.sign + "と" + c.person2.byKey.sun.sign + "）：" + SIGN_REL[c.sun].text },
      moon: { label: SIGN_REL[c.moon].label, text: "月どうし（" + c.person1.byKey.moon.sign + "と" + c.person2.byKey.moon.sign + "）：" + SIGN_REL[c.moon].text },
      aspects: c.aspects.map(function (a) {
        return { title: "あなたの" + a.youName + " × お相手の" + a.partnerName + "：" + a.aspectName, text: SYN_THEME[a.you + "-" + a.partner] + SYN_TYPE[a.aspect], tone: ASPECT_TYPE[a.aspect].tone };
      })
    };
  }

