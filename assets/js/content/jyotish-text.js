  function band(score) {
    if (score >= 33) return { label: "最高の相性", text: "8つの項目のほとんどで調和している、インド占星術でも理想とされる組み合わせです。" };
    if (score >= 25) return { label: "とても良い相性", text: "多くの項目で調和していて、安定した関係を築きやすい組み合わせです。" };
    if (score >= 18) return { label: "良い相性", text: "インド占星術で「結婚に向いている」とされる18点以上の組み合わせ。足りない項目は、ふたりの思いやりで補えます。" };
    return { label: "工夫が必要な相性", text: "18点未満は、伝統的には慎重に考えるべきとされる組み合わせです。ただし点数は関係のすべてではありません。低い項目を知って、意識して補い合うことが大切です。" };
  }

